'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {spawnSync}=require('node:child_process');
const file=path.join(__dirname,'CSHARP-MORE-583.cs');
const source=fs.readFileSync(file,'utf8');
const ids=[...source.matchAll(/^static class E(\d{3,4}) \{/gm)].map(m=>Number(m[1]));
assert.deepEqual(ids,Array.from({length:583},(_,i)=>i+584),'583 unique C# classes, E584..E1166');
assert.equal((source.match(/public static .* Practice(?:<T>)?\(/g)||[]).length,583);
assert.equal((source.match(/public static .* Reference(?:<T>)?\(/g)||[]).length,583);
const option=process.argv.find(a=>a.startsWith('--id='));
const practice=process.argv.includes('--starters');
if(practice&&!option)throw new Error('Practice requires --id=N');
const args=['run','--file',file,'--',practice?'--practice':'--verify'];
if(option)args.push(option.slice(5));
const run=spawnSync('dotnet',args,{cwd:__dirname,encoding:'utf8',timeout:600000,maxBuffer:8*1024*1024});
process.stdout.write(run.stdout||'');process.stderr.write(run.stderr||'');
if(run.error)console.error(run.error.message);
const expected=option?1:583;
const summary=new RegExp((practice?'Practice':'Reference')+': '+expected+' passed, 0 failed;');
process.exitCode=run.status===0&&summary.test(run.stdout||'')?0:1;
